function hash(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}

function isRecord(value) {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

function sameKeys(actual, expected) {
  return isRecord(actual) && Object.keys(actual).sort().join("\0") === [...expected].sort().join("\0");
}

function stable(value) {
  if (Array.isArray(value)) return value.map(stable);
  if (isRecord(value)) return Object.fromEntries(Object.keys(value).sort().map((key) => [key, stable(value[key])]));
  return value;
}

function sameValue(left, right) {
  return JSON.stringify(stable(left)) === JSON.stringify(stable(right));
}

function walkPackage(root, onEntry, prefix = "") {
  for (const entry of readdirSync(root, { withFileTypes: true })) {
    const abs = join(root, entry.name);
    const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
    const stat = lstatSync(abs);
    onEntry(rel, abs, stat);
    if (stat.isDirectory()) walkPackage(abs, onEntry, rel);
  }
}

function expectedClass(binding) {
  if (binding.definition.name === "reset_paper_account") return "Sensitive write";
  if (PAPER_WRITE_TOOLS.has(binding.definition.name)) return "Write";
  return "Read";
}

function fieldLimits(schema) {
  const rows = [];
  const properties = schema?.properties ?? {};
  for (const [name, field] of Object.entries(properties)) {
    const parts = [`\`${name}\``, field.type ?? "any"];
    if (schema.required?.includes(name)) parts.push("required");
    if (field.enum) parts.push(`one of ${field.enum.map((value) => `\`${JSON.stringify(value)}\``).join(", ")}`);
    for (const key of ["minimum", "maximum", "exclusiveMinimum", "exclusiveMaximum", "minLength", "maxLength", "minItems", "maxItems", "pattern", "default"]) {
      if (field[key] !== undefined) parts.push(`${key}=${JSON.stringify(field[key])}`);
    }
    rows.push(`- ${parts.join("; ")}`);
  }
  return rows.length ? rows.join("\n") : "- No input properties are declared.";
}

function sourceRel(repoRoot, path) {
  return relative(repoRoot, path).split(sep).join("/");
}

