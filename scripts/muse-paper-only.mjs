export function validateMusePackage(repoRootInput) {
  const repoRoot = resolve(repoRootInput);
  const errors = [];
  const packagesRoot = join(repoRoot, "plugins");
  const discoveries = [];
  const validateManifest = new Ajv2020({ allErrors: true, strict: false }).compile(JSON.parse(readFileSync(join(repoRoot, "schemas/agent-plugins/plugin.schema.json"), "utf8")));
  const validateMcp = new Ajv2020({ allErrors: true, strict: false }).compile(JSON.parse(readFileSync(join(repoRoot, "schemas/agent-plugins/mcp.schema.json"), "utf8")));
  if (existsSync(packagesRoot)) {
    for (const entry of readdirSync(packagesRoot, { withFileTypes: true })) {
      if (!entry.isDirectory() && !(entry.name === "co-invest-muse" && entry.isSymbolicLink())) continue;
      const dir = join(packagesRoot, entry.name);
      const manifest = join(dir, "plugin.json");
      if (existsSync(manifest) || entry.name === "co-invest-muse") discoveries.push({ name: entry.name, dir, manifest });
    }
  }

  const names = new Set();
  for (const pkg of discoveries) {
    let manifest;
    try {
      manifest = JSON.parse(readFileSync(pkg.manifest, "utf8"));
    } catch (err) {
      errors.push(`${sourceRel(repoRoot, pkg.manifest)}: cannot parse Agent Plugins manifest (${err.message})`);
      continue;
    }
    if (!validateManifest(manifest)) {
      for (const issue of validateManifest.errors ?? []) errors.push(`${sourceRel(repoRoot, pkg.manifest)}: ${issue.instancePath || "(root)"} ${issue.message}`);
    }
    if (!isRecord(manifest) || typeof manifest.name !== "string") continue;
    if (names.has(manifest.name)) errors.push(`${sourceRel(repoRoot, pkg.manifest)}: duplicate Agent Plugins identifier "${manifest.name}"`);
    names.add(manifest.name);
    const mcpPath = join(pkg.dir, "mcp.json");
    if (existsSync(mcpPath)) {
      try {
        const mcp = JSON.parse(readFileSync(mcpPath, "utf8"));
        if (!validateMcp(mcp)) {
          for (const issue of validateMcp.errors ?? []) errors.push(`${sourceRel(repoRoot, mcpPath)}: ${issue.instancePath || "(root)"} ${issue.message}`);
        }
      } catch (err) {
        errors.push(`${sourceRel(repoRoot, mcpPath)}: cannot parse MCP configuration (${err.message})`);
      }
    }
    if (pkg.name !== "co-invest-muse" && manifest.name !== "co-invest-muse") continue;
    validateCoInvestMuse(repoRoot, pkg.dir, manifest, errors);
  }

  return { errors, packageCount: discoveries.length };
}

function validateCoInvestMuse(repoRoot, dir, manifest, errors) {
  const rel = (path) => sourceRel(repoRoot, path);
  const manifestPath = join(dir, "plugin.json");
  const mcpPath = join(dir, "mcp.json");
  const contractPath = join(dir, "paper-only.contract.json");
  const examplesPath = join(dir, "paper-only.examples.json");
  const sourcePath = join(dir, "paper-only.source.json");
  const toolsPath = join(dir, "tools.md");
  const report = (path, message) => errors.push(`${rel(path)}: ${message}`);
  if (lstatSync(dir).isSymbolicLink()) {
    report(dir, "package root symlink is not allowed");
    return;
  }

  const requiredManifest = {
    $schema: "https://agent-plugins.org/schemas/1.0.0/plugin.schema.json",
    name: "co-invest-muse",
    version: "1.0.0",
    description: "Research markets and practice simulated trading with Liquid Co-Invest in Muse. Orders placed through this connector are simulated. Signing in uses your normal Liquid account permission, which is not limited to practice trading.",
    author: { name: "Liquid", url: "https://liquid.trade" },
    homepage: "https://liquid.trade/coinvest",
    repository: "https://github.com/LiquidMax-dev/liquid-plugin",
    license: "MIT",
    keywords: ["liquid", "Co-Invest", "paper trading", "markets", "mcp"],
  };
  if (!sameValue(manifest, requiredManifest)) {
    report(manifestPath, "must match the reviewed co-invest-muse Agent Plugins manifest exactly");
  }

  let mcp;
  try {
    mcp = JSON.parse(readFileSync(mcpPath, "utf8"));
  } catch (err) {
    report(mcpPath, `cannot parse MCP configuration (${err.message})`);
  }
  const expectedMcp = {
    $schema: "https://agent-plugins.org/schemas/1.0.0/mcp.schema.json",
    mcpServers: { "Co-Invest": { type: "streamable-http", url: PAPER_ONLY_ENDPOINT } },
  };
  if (mcp && !sameValue(mcp, expectedMcp)) {
    report(mcpPath, `must contain only the canonical streamable-http endpoint ${PAPER_ONLY_ENDPOINT}`);
  }

  const actualFiles = new Set();
  if (existsSync(dir)) {
    walkPackage(dir, (path, abs, stat) => {
      if (stat.isSymbolicLink()) report(abs, "symlinks are not allowed in the connector package");
      if (stat.isFile()) actualFiles.add(path);
      else if (stat.isDirectory() && !PACKAGE_DIRS.has(path)) report(abs, "directory is outside the reviewed Muse package scope");
      else if (!stat.isDirectory()) report(abs, "package entries must be regular files or directories");
    });
  }
  for (const path of actualFiles) {
    if (!PACKAGE_FILES.has(path)) report(join(dir, path), "file is outside the reviewed Muse package scope");
  }
  for (const expected of PACKAGE_FILES) {
    if (!actualFiles.has(expected)) report(join(dir, expected), "required Muse package file is missing");
  }

  for (const file of actualFiles) {
    const abs = join(dir, file);
    const text = readFileSync(abs, "utf8");
    if (/-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----|\b(?:ghp|github_pat|sk_live|sk_test)_[A-Za-z0-9_-]{12,}|\bBearer\s+[A-Za-z0-9._~+/-]{16,}|\b(?:api[_-]?key|client[_-]?secret|access[_-]?token|refresh[_-]?token)\s*[:=]\s*["']?[A-Za-z0-9._~+/-]{12,}/i.test(text)) {
      report(abs, "possible credential or private key detected");
    }
    if (/(?:^|["\s])(?:\/Users\/|\/home\/)[^\s"']+/m.test(text)) {
      report(abs, "machine-specific absolute path is not allowed in the portable package");
    }
  }

  let contract;
  let examples;
  let source;
  try { contract = JSON.parse(readFileSync(contractPath, "utf8")); }
  catch (err) { report(contractPath, `cannot parse contract snapshot (${err.message})`); }
  try { examples = JSON.parse(readFileSync(examplesPath, "utf8")); }
  catch (err) { report(examplesPath, `cannot parse representative examples (${err.message})`); }
  try { source = JSON.parse(readFileSync(sourcePath, "utf8")); }
  catch (err) { report(sourcePath, `cannot parse source metadata (${err.message})`); }
  if (!contract || !examples || !source) return;

  if (contract.profile !== "paper-only" || contract.formatVersion !== 1 || !Array.isArray(contract.bindings) || contract.bindings.length !== 45) {
    report(contractPath, "must be the complete version 1 paper-only contract with 45 bindings");
  }
  const contractBytes = readFileSync(contractPath);
  const examplesBytes = readFileSync(examplesPath);
  if (!sameKeys(source, ["formatVersion", "sourceRevision", "contractHash", "contractSha256", "examplesSha256"])) {
    report(sourcePath, "must contain only the pinned revision and contract/example integrity metadata");
  }
  if (source.formatVersion !== 1 || !/^[0-9a-f]{40}$/.test(source.sourceRevision ?? "")) report(sourcePath, "sourceRevision must be a full git SHA");
  if (source.contractHash !== contract.contractHash) report(sourcePath, "contractHash does not match the copied contract");
  if (source.contractSha256 !== hash(contractBytes)) report(sourcePath, "contract SHA-256 does not match the copied contract bytes");
  if (source.contractHash !== PAPER_ONLY_CONTRACT_HASH) report(sourcePath, "contractHash is not the reviewed paper-only profile hash");
  if (source.contractSha256 !== PAPER_ONLY_CONTRACT_FILE_SHA256) report(sourcePath, "contract file SHA-256 is not the reviewed paper-only snapshot");
  if (source.examplesSha256 !== hash(examplesBytes)) report(sourcePath, "examples SHA-256 does not match the copied example bytes");

  if (!Array.isArray(contract.bindings)) return;

  if (!sameKeys(examples, ["formatVersion", "profile", "tools"]) || examples.formatVersion !== 1 || examples.profile !== "paper-only" || !isRecord(examples.tools)) {
    report(examplesPath, "must contain version 1 paper-only representative tool examples");
    return;
  }
  const contractNames = new Set();
  for (const binding of contract.bindings) {
    const name = binding?.definition?.name;
    if (typeof name !== "string" || !MCP_TOOL_ID_RE.test(name)) {
      report(contractPath, `tool identifier "${name}" is invalid`);
      continue;
    }
    if (contractNames.has(name)) report(contractPath, `duplicate tool identifier "${name}"`);
    contractNames.add(name);
    if (!PAPER_ONLY_TOOL_NAMES.has(name)) report(contractPath, `tool "${name}" is outside the approved paper-only scope`);
    const requiredEffect = REQUIRED_EFFECTS.get(name);
    if (requiredEffect && !binding.effects?.includes(requiredEffect)) {
      report(contractPath, `tool "${name}" must declare the ${requiredEffect} effect`);
    }
    if (requiredEffect && name !== "edit_watchlist" && binding.effects?.some((effect) => effect.endsWith("-write"))) {
      report(contractPath, `read-only utility "${name}" cannot declare a write effect`);
    }
    if (PAPER_WRITE_TOOLS.has(name) && !binding.effects?.some((effect) => effect.endsWith("-write"))) {
      report(contractPath, `state-changing tool "${name}" is missing its write effect`);
    }
    if (name === "reset_paper_account" && (!binding.effects?.includes("paper-account-write") || binding.approval !== "direct-request")) {
      report(contractPath, "reset_paper_account must remain a direct-request paper-account write");
    }
    if (name === "edit_watchlist" && binding.approval !== "direct-request") {
      report(contractPath, "edit_watchlist must remain a direct-request shared preference write");
    }
    if (PAPER_WRITE_TOOLS.has(name) && !["confirmed-argument", "direct-request"].includes(binding.approval)) {
      report(contractPath, `state-changing tool "${name}" has unexpected approval metadata`);
    }
    const example = examples.tools[name];
    if (!isRecord(example) || !sameKeys(example, ["input", "expected"]) || !isRecord(example.input) || !isRecord(example.expected) || typeof example.expected.outcome !== "string" || !Array.isArray(example.expected.assertions)) {
      report(examplesPath, `missing or malformed representative case for "${name}"`);
      continue;
    }
    if (!sameKeys(example.expected, ["outcome", "assertions"])) {
      report(examplesPath, `case for "${name}" contains fields outside input, outcome, and assertions`);
    }
  }
  for (const name of PAPER_ONLY_TOOL_NAMES) {
    if (!contractNames.has(name)) report(contractPath, `approved paper-only tool "${name}" is missing from the contract`);
  }
  for (const name of Object.keys(examples.tools)) {
    if (!contractNames.has(name)) report(examplesPath, `example "${name}" is not present in the pinned contract`);
  }
  if (!actualFiles.has("tools.md")) return;
  const docs = readFileSync(toolsPath, "utf8");
  if (!docs.startsWith("# Paper-only MCP tools\n") || !docs.includes(TOOL_REFERENCE_GENERATED)) report(toolsPath, "is missing the generated reference marker");
  try {
    const regenerated = renderTools(contract, examples, source);
    if (docs !== regenerated) report(toolsPath, "does not match deterministic generation (run npm run sync:muse-paper-only -- --check)");
  } catch (err) {
    report(toolsPath, `cannot regenerate tool reference (${err.message})`);
  }
}
